#!/usr/bin/env python3
# The hyphenated script name is not a valid module name
# pylint: disable=invalid-name
"""Render the device's statistics counters into the documentation.

The counter sets are defined in C and nowhere else: the LIF statistics
block names its counters in ``src/ionic_emu_stats.c``, and the two
tables a guest reads through ``hw_counters`` are ``dev_stats`` and
``qp_stats`` in ``src/ionic_adminq_priv.h``.  Prose that restates them
goes stale the first time one is added, and the published site is the
last place that shows up.

So the lists under ``docs/generated/`` are built from those files
rather than written, and ``docs/monitoring.rst`` includes them.  The
sphinx-html target regenerates them, Docs Check fails a change that
edits a counter without rerunning this, and the generated files are
committed so a plain ``sphinx-build`` renders a complete page.

A parse that comes back empty, or a name without an offset, is an
error rather than a short list: a silently empty table is exactly the
staleness this exists to prevent.

Copyright (c) Advanced Micro Devices, Inc. All rights reserved.

SPDX-License-Identifier: MIT
"""

import argparse
import pathlib
import re
import sys

# Where each counter set is defined, relative to the repository root.
LIF_ENUM_SRC = "src/ionic_emu_stats.h"
LIF_NAMES_SRC = "src/ionic_emu_stats.c"
HW_TABLES_SRC = "src/ionic_adminq_priv.h"

OUT_DIR = "docs/generated"

# struct ionic_lif_stats is 128 qwords; a counter outside that is a
# parse that went wrong, not a counter.
LIF_STATS_QWORDS = 128

# Which group a LIF counter belongs to, by its name.  First match wins,
# so the RDMA rules come before the generic ones: rdma_resp_rx_cqe_err
# is an RDMA error, not a ring error.
GROUPS = (
    (re.compile(r"^rdma_(req|resp)_"), "RDMA error"),
    (re.compile(r"_rdma_"), "RDMA traffic"),
    (re.compile(r"_drop_|_dma_error$"), "Drop and DMA error"),
    (re.compile(r"_queue_|_desc_"), "Ring error"),
    (re.compile(r"."), "Ethernet traffic"),
)

# The order the groups are described in, which is also the order the
# counters appear in the block.
GROUP_ORDER = (
    "Ethernet traffic",
    "Drop and DMA error",
    "Ring error",
    "RDMA traffic",
    "RDMA error",
)

# The trailing newline is load-bearing: joining the lines puts one more
# after it, and a comment block that is not followed by a blank line is
# a docutils warning.
HEADER = """.. Generated by tools/gen-counter-docs.py from {sources}.
   Do not edit: run ``python3 tools/gen-counter-docs.py`` instead.
"""


def read(root, relative):
    """The text of a source file, or a clear failure."""
    path = root / relative
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        raise SystemExit(f"{path}: {exc}") from exc


def group_of(name):
    """The group a LIF counter name belongs to."""
    for pattern, group in GROUPS:
        if pattern.search(name):
            return group
    raise SystemExit(f"no group matched {name!r}")


def parse_lif_counters(root):
    """The LIF block's counters as [(qword, name, group)], in block order.

    The qword index comes from the enum in the header and the name from
    the table in the C file; a counter named by one and not the other is
    an error, because that is the case where the docs would quietly
    disagree with the device.
    """
    enum_text = read(root, LIF_ENUM_SRC)
    index = {
        match.group(1): int(match.group(2))
        for match in re.finditer(
            r"^\s*(IONIC_LIF_[A-Z0-9_]+)\s*=\s*(\d+)\s*,", enum_text, re.MULTILINE
        )
    }
    if not index:
        raise SystemExit(f"{LIF_ENUM_SRC}: no enum ionic_lif_stat entries found")

    names_text = read(root, LIF_NAMES_SRC)
    # The initialiser wraps for the longer names, so the string can be
    # on the line after the designator.
    names = {
        match.group(1): match.group(2)
        for match in re.finditer(
            r"\[(IONIC_LIF_[A-Z0-9_]+)\]\s*=\s*\"([a-z0-9_]+)\"", names_text
        )
    }
    if not names:
        raise SystemExit(f"{LIF_NAMES_SRC}: no counter names found")

    missing = sorted(set(names) - set(index))
    if missing:
        raise SystemExit(
            f"{LIF_NAMES_SRC}: named counters with no qword index: "
            f"{', '.join(missing)}"
        )

    counters = []
    for symbol, name in names.items():
        qword = index[symbol]
        if qword >= LIF_STATS_QWORDS:
            raise SystemExit(f"{name}: qword {qword} is outside the stats block")
        counters.append((qword, name, group_of(name)))

    counters.sort()
    qwords = [qword for qword, _, _ in counters]
    if len(set(qwords)) != len(qwords):
        raise SystemExit(f"{LIF_NAMES_SRC}: two counters share a qword index")
    return counters


# An initialiser that builds entries from a list macro rather than
# writing them out -- IONIC_DP_RDMA_COUNTERS(DEV_RDMA_STAT) and the like.
# Reading the names out of one means expanding it, which is a C
# preprocessor's job and not this script's.
MACRO_ENTRY = re.compile(r"\b([A-Z][A-Z0-9_]{2,})\s*\(")


def parse_hw_table(text, table):
    """The counter names of one adminq_stat table, in table order.

    Only literal ``{"name", offsetof(...)}`` entries are understood. A
    table that generates entries from a list macro is refused rather
    than half-read: the counters it adds are real, and a short list here
    is the silent staleness this script exists to prevent. Teach the
    parser the macro, or write the entries out.
    """
    # Up to the first "};", wherever it sits: an entry ends in ")}," so
    # the first "};" is the end of the table. Anchoring on "\n};" instead
    # would run past a table whose last entry shares the closing line,
    # swallowing whatever was declared after it.
    match = re.search(rf"adminq_stat\s+{table}\[\]\s*=\s*\{{(.*?)\}};", text, re.DOTALL)
    if not match:
        raise SystemExit(f"{HW_TABLES_SRC}: table {table} not found")
    body = match.group(1)

    # offsetof() is how every literal entry names its field, so it is the
    # one all-caps-looking call that does not mean a generated entry.
    generated = {name for name in MACRO_ENTRY.findall(body) if name != "OFFSETOF"}
    if generated:
        raise SystemExit(
            f"{HW_TABLES_SRC}: table {table} builds entries with "
            f"{', '.join(sorted(generated))}, which this script cannot "
            f"expand. Its counters would be missing from the docs."
        )

    names = re.findall(r"\{\s*\"([a-z0-9_]+)\"", body)
    if not names:
        raise SystemExit(f"{HW_TABLES_SRC}: table {table} names no counters")
    if len(set(names)) != len(names):
        raise SystemExit(f"{HW_TABLES_SRC}: table {table} repeats a counter name")
    return names


def rst_table(rows, headers, widths):
    """A list-table, which wraps better at 80 columns than a grid."""
    out = [".. list-table::", "   :header-rows: 1", f"   :widths: {widths}", ""]
    for row in (headers, *rows):
        for i, cell in enumerate(row):
            out.append(f"   {'*' if i == 0 else ' '} - {cell}")
    out.append("")
    return out


def render_lif(counters):
    """The LIF counter reference."""
    out = [HEADER.format(sources=f"``{LIF_NAMES_SRC}``")]
    by_group = {group: [] for group in GROUP_ORDER}
    for qword, name, group in counters:
        by_group[group].append((qword, name))

    out.append(f"The block has {len(counters)} named counters:")
    out.append("")
    for group in GROUP_ORDER:
        members = by_group[group]
        if not members:
            continue
        out.append(f"* {group}: {len(members)} counters, from")
        out.append(f"  ``{members[0][1]}`` to ``{members[-1][1]}``.")
    out.append("")
    out.append("Every one of them, with its qword index in")
    out.append("``struct ionic_lif_stats``:")
    out.append("")
    out.extend(
        rst_table(
            [(str(qword), f"``{name}``", group) for qword, name, group in counters],
            ("Qword", "Counter", "Group"),
            "10 48 42",
        )
    )
    return "\n".join(out) + "\n"


def render_hw(dev_stats, qp_stats):
    """The two tables a guest reads through hw_counters."""
    out = [HEADER.format(sources=f"``{HW_TABLES_SRC}``")]
    out.append(f"The device table, {len(dev_stats)} counters:")
    out.append("")
    out.extend(
        rst_table(
            [(f"``{name}``",) for name in dev_stats],
            ("Counter",),
            "100",
        )
    )
    out.append(f"The per-QP table, {len(qp_stats)} counters:")
    out.append("")
    out.extend(
        rst_table(
            [(f"``{name}``",) for name in qp_stats],
            ("Counter",),
            "100",
        )
    )
    return "\n".join(out) + "\n"


def main():
    """Write the generated pages, or report what has gone stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        default=pathlib.Path(__file__).resolve().parent.parent,
        type=pathlib.Path,
        help="repository root (default: the one this script lives in)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed files are not what this would write",
    )
    args = parser.parse_args()
    root = args.root

    counters = parse_lif_counters(root)
    hw_text = read(root, HW_TABLES_SRC)
    pages = {
        "lif-counters.rst": render_lif(counters),
        "hw-counter-tables.rst": render_hw(
            parse_hw_table(hw_text, "dev_stats"),
            parse_hw_table(hw_text, "qp_stats"),
        ),
    }

    out_dir = root / OUT_DIR
    stale = []
    for name, text in pages.items():
        path = out_dir / name
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            if current != text:
                stale.append(path)
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    if stale:
        for path in stale:
            print(f"{path}: out of date", file=sys.stderr)
        print(
            "Run: python3 tools/gen-counter-docs.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
