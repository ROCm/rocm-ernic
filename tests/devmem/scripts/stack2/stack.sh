# Drive the ionic devmem-RX test stack (stack 2) with qemu-tool 2.0.0 (run with uvx from
# the scratch clone, never the stale ~/.local/bin/qemu-tool).
#
#   stack.sh render            re-render the stack from the fleet XML + write the override
#   stack.sh up                start it (containers + guests), wait for ssh on both guests
#   stack.sh down              power the guests off cleanly, then compose down
#   stack.sh restart           down, up
#   stack.sh status            qemu-tool list + compose ps + which server binary is in use
#   stack.sh server image      use the rocm-ernic binary of the <ernic-ref> image (default)
#   stack.sh server /abs/path/to/rocm-ernic
#                              bind-mount a locally built server over the image's
#                              /usr/local/bin/rocm-ernic in both ernic containers
#                              (build it with scripts/build-ernic.sh), then restart
#   stack.sh server-args none|ARGS...
#                              extra rocm-ernic options for both ernic containers,
#                              e.g. `server-args --nic-profile header-split` (the
#                              RX header-split mode); needs a local server binary
#                              (`stack.sh server /abs/path`); then restart
#   stack.sh qt ARGS...        run qemu-tool 2.0.0 with ARGS
#   stack.sh compose ARGS...   qemu-tool compose against this stack (logs, ps, ...)
#
# Stack directory (= compose project "ionic-devmem-rx"): test-rx/stack/ionic-devmem-rx
# Guest disks: test-rx/images/rx-{1,2}.qcow2 (overlays; they survive down/up).
set -euo pipefail
T=${DEVMEM_ROOT:?set it to the work area}/test-rx
QM=${DEVMEM_ROOT:?set it to the work area}/qemu-minimal
STACK=$T/stack/ionic-devmem-rx
XML=(--xml "$QM/qemu/stacks/rocm-golden.xml" --xml "$T/stack/rx-fleet.xml")
SERVER_FILE=$T/stack/server-binary.path # absent = image's own binary
# Extra server options, one line; absent or empty = none. gen-compose has no
# pass-through for them, so with a local binary the override mounts that at
# REAL_BIN and a wrapper (WRAPPER) that appends the options over the image's.
ARGS_FILE=$T/stack/server-args
WRAPPER=$T/stack/rocm-ernic-wrapper.sh
REAL_BIN=/opt/rocm-ernic-local/rocm-ernic
S=$(dirname "$(readlink -f "$0")")

qt() { uvx --from "$QM/qemu" qemu-tool "$@"; }

write_override() {
    local svc bin="" args=""
    [ -s "$SERVER_FILE" ] && bin=$(cat "$SERVER_FILE")
    [ -s "$ARGS_FILE" ] && args=$(cat "$ARGS_FILE")
    if [ -n "$args" ]; then
        [ -n "$bin" ] || { echo "server-args needs a local server binary (stack.sh server /abs/path)" >&2; exit 1; }
        printf '#!/bin/sh\nexec %s "$@" %s\n' "$REAL_BIN" "$args" >"$WRAPPER"
        chmod 755 "$WRAPPER"
    fi
    {
        cat <<'EOF'
# Written by /var/tmp/ionic-devmem/test-rx/scripts/stack.sh; not generated by
# qemu-tool. docker compose loads it automatically beside docker-compose.yml.
#
# cgroup_parent: this host's dockerd (24.0.7, systemd cgroup driver) refuses
# any container that names no cgroup parent ("cgroup-parent for systemd
# cgroup should be a valid slice named as xxx.slice"), `docker run` included.
#
# volumes on ernic-N (only when a local server binary is selected): the
# locally built rocm-ernic replaces the image's /usr/local/bin/rocm-ernic.
services:
EOF
        for svc in rocjitsu-1 rocjitsu-2 qemu-1 qemu-2 tapsetup-1 tapsetup-2; do
            echo "  $svc: {cgroup_parent: system.slice}"
        done
        for svc in ernic-1 ernic-2; do
            echo "  $svc:"
            echo "    cgroup_parent: system.slice"
            if [ -n "$bin" ] && [ -n "$args" ]; then
                echo "    volumes:"
                echo "      - \"$bin:$REAL_BIN:ro\""
                echo "      - \"$WRAPPER:/usr/local/bin/rocm-ernic:ro\""
            elif [ -n "$bin" ]; then
                echo "    volumes:"
                echo "      - \"$bin:/usr/local/bin/rocm-ernic:ro\""
            fi
        done
        # Guest Ethernet crosses the docker network "l2"; its default MTU
        # of 1500 drops jumbo frames between the two ernic containers.
        # jumbo() below raises tap0/br0 inside the containers to match.
        cat <<'EOF'
networks:
  l2:
    driver_opts:
      com.docker.network.driver.mtu: "9216"
EOF
    } >"$STACK/docker-compose.override.yml"
}

# tap0 and br0 in each ernic container are created at MTU 1500 by the
# tapsetup sidecar; raise them so guest MTUs up to the ionic maximum (9198)
# pass. One-off container in the ernic's netns, NET_ADMIN only.
jumbo() {
    local n
    for n in 1 2; do
        "$S/drun.sh" --network "container:ionic-devmem-rx-ernic-$n-1" --cap-drop ALL \
            --cap-add NET_ADMIN --entrypoint /bin/sh qemu-tool/ernic-tapsetup:1 -c \
            'ip link set tap0 mtu 9216 && ip link set br0 mtu 9216; ip -o link | cut -d" " -f2,4,5 | tr "\n" " "'
        echo
    done
}

wait_ssh() {
    local n i
    for n in 1 2; do
        for i in $(seq 150); do
            "$S/gssh" "$n" true 2>/dev/null && break
            [ "$i" = 150 ] && { echo "rx-$n: no ssh" >&2; return 1; }
            sleep 2
        done
        echo "rx-$n: $("$S/gssh" "$n" 'uname -r; ip -br addr show rocm-ernic0' | tr '\n' ' ')"
    done
}

cmd=${1:-status}
shift || true
case "$cmd" in
render)
    qt gen-compose "${XML[@]}" --output-dir "$STACK"
    write_override
    ;;
up)
    [ -e "$STACK/docker-compose.yml" ] || "$0" render
    write_override
    qt compose --stack-dir "$STACK" "${XML[@]}" up -d
    jumbo
    wait_ssh
    ;;
down)
    # Guest-agent poweroff first: `docker compose down` alone is a power cut.
    # On this host `docker exec` delivers no stdout, so qemu-tool cannot read
    # the agent's answer: it prints "shutdown not requested ()" / "no guest
    # accepted a shutdown request" and exits 1 although the guests ARE
    # powering off. So ignore its status, wait for the qemu containers to
    # exit (ssh poweroff as the fallback), then remove the stack.
    # Stack 2: never call `qt down` by name (stack 1 lives beside us); ask each
    # guest to power off over ssh instead.
    for n in 1 2; do timeout 20 "$S/gssh" "$n" 'sudo systemd-run --on-active=1 systemctl poweroff' >/dev/null 2>&1 || true; done
    for n in 1 2; do
        c=ionic-devmem-rx-qemu-$n-1
        for i in $(seq 90); do
            st=$(docker inspect -f '{{.State.Status}}' "$c" 2>/dev/null || echo gone)
            [ "$st" != running ] && break
            [ "$i" = 15 ] && "$S/gssh" "$n" 'sudo systemctl poweroff' 2>/dev/null || true
            [ "$i" = 90 ] && echo "rx-$n still running; compose down will kill it" >&2
            sleep 2
        done
    done
    qt compose --stack-dir "$STACK" "${XML[@]}" down
    ;;
restart)
    "$0" down
    "$0" up
    ;;
jumbo) jumbo ;;
status)
    qt list
    qt compose --stack-dir "$STACK" "${XML[@]}" ps -a
    if [ -s "$SERVER_FILE" ]; then
        echo "server binary: $(cat "$SERVER_FILE") (bind-mounted)"
    else
        echo "server binary: the <ernic-ref> image's own"
    fi
    [ -s "$ARGS_FILE" ] && echo "server args: $(cat "$ARGS_FILE")"
    for n in 1 2; do
        echo "ernic-$n binds: $(docker inspect -f '{{range .Mounts}}{{if eq .Type "bind"}}{{.Source}} {{end}}{{end}}' "ionic-devmem-rx-ernic-$n-1" 2>/dev/null)"
    done
    ;;
server)
    what=${1:?usage: stack.sh server image|/abs/path/to/rocm-ernic}
    if [ "$what" = image ]; then
        : >"$SERVER_FILE"
    else
        [ -x "$what" ] || { echo "$what: not an executable" >&2; exit 1; }
        case "$what" in /*) ;; *) echo "need an absolute path" >&2; exit 1 ;; esac
        echo "$what" >"$SERVER_FILE"
    fi
    # Never restart only the ernic containers: a manager (ernic-1) restart
    # wedges every guest (qemu-minimal AGENTS.md, known issue 7).
    "$0" restart
    ;;
server-args)
    [ $# -ge 1 ] || { echo "usage: stack.sh server-args none|ARGS..." >&2; exit 1; }
    if [ "$1" = none ]; then
        : >"$ARGS_FILE"
    else
        [ -s "$SERVER_FILE" ] || { echo "select a local server binary first: stack.sh server /abs/path" >&2; exit 1; }
        echo "$*" >"$ARGS_FILE"
    fi
    "$0" restart
    ;;
qt) qt "$@" ;;
compose) qt compose --stack-dir "$STACK" "${XML[@]}" "$@" ;;
*)
    sed -n '2,20p' "$0"
    exit 2
    ;;
esac
